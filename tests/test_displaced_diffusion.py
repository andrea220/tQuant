EVAL_DATE = date(2026, 5, 15)
S0 = 100.0
STRIKES = [60.0, 70.0, 80.0, 90.0, 100.0, 110.0, 120.0, 130.0, 140.0]
NODES = [0.5, 1.0, 2.0]
BETA_FWD, SIGMA_FWD = [0.8, 0.5, 0.3], [0.25, 0.20, 0.18]
A365 = DayCounterConvention.Actual365


def dd_market(beta_fwd=BETA_FWD, sigma_fwd=SIGMA_FWD) -> MarketEnvironment:
    """Market whose smile is generated by a displaced diffusion with the given forward parameters."""
    tq.Settings.evaluation_date = EVAL_DATE
    surface = VolatilitySurface(EVAL_DATE, None, DayCounter(A365), STRIKES, NODES, [[0.2] * len(STRIKES)] * len(NODES))
    mkt = MarketEnvironment(market={
        "IR:EUR:ESTR:SPOT": tq.RateCurve(EVAL_DATE, [0.5, 1.0, 2.0, 5.0], [0.020, 0.022, 0.024, 0.026], "LINEAR", A365),
        "EQ:EUR:DD:SPOT": S0, "EQ:EUR:DD:REPO": 0.005, "EQ:EUR:DD:DIVYIELD": 0.02, "EQ:EUR:DD:VOL": surface,
    })
    eq = mkt.get_equity("DD")
    truth = DisplacedDiffusionModel(eq, NODES, beta_fwd, sigma_fwd)
    surface.volatility_matrix.assign([[truth.implied_vol(K, T) for K in STRIKES] for T in NODES])
    return mkt


def black(k, vol, t):
    sd = vol * np.sqrt(t)
    d1 = -np.log(k) / sd + 0.5 * sd
    return norm.cdf(d1) - k * norm.cdf(d1 - sd)


def bachelier(k, vol, t):
    sd = vol * np.sqrt(t)
    return (1.0 - k) * norm.cdf((1.0 - k) / sd) + sd * norm.pdf((1.0 - k) / sd)


class TestClosedForm(unittest.TestCase):
    def test_limits_and_parity(self):
        """beta = 1: Black; beta -> 0: Bachelier with normal vol sigma (per unit forward); C - P = 1 - k."""
        k = np.array([0.7, 1.0, 1.3])
        np.testing.assert_allclose(displaced_diffusion_price(k, 1.0, 0.25, 2.0).numpy(), black(k, 0.25, 2.0), rtol=1e-14)
        np.testing.assert_allclose(displaced_diffusion_price(k, 1e-5, 0.25, 2.0).numpy(), bachelier(k, 0.25, 2.0), rtol=1e-4)
        for beta in (0.3, 0.8, 1.3):
            c = displaced_diffusion_price(k, beta, 0.2, 1.5).numpy()
            p = displaced_diffusion_price(k, beta, 0.2, 1.5, phi=-1.0).numpy()
            np.testing.assert_allclose(c - p, 1.0 - k, atol=1e-15)
            self.assertTrue(np.all(p >= 0.0))
        # shifted strike <= 0 (beta > 1, low strike): always exercised
        self.assertAlmostEqual(float(displaced_diffusion_price(0.2, 1.4, 0.2, 1.0)), 0.8, places=15)

    def test_lower_beta_steeper_skew(self):
        """Lower beta, steeper negative skew; the steepest (normal) ATM skew is about -sigma / 2."""
        skews = []
        for beta in (1.0, 0.5, 0.02):
            vols = [_black_implied_vol(float(displaced_diffusion_price(k, beta, 0.2, 1.0)), k, 1.0) for k in (0.99, 1.01)]
            skews.append((vols[1] - vols[0]) / np.log(1.01 / 0.99))
        self.assertAlmostEqual(skews[0], 0.0, delta=1e-6)
        self.assertLess(skews[2], skews[1])
        self.assertLess(skews[1], 0.0)
        self.assertAlmostEqual(skews[2], -0.1, delta=0.01)


class TestSkewAveraging(unittest.TestCase):
    def test_round_trip_and_constant_beta(self):
        model = DisplacedDiffusionModel(dd_market().get_equity("DD"), NODES, BETA_FWD, SIGMA_FWD)
        beta_t, sigma_t = model.effective_parameters(NODES)
        beta_f, sigma_f, floored = forward_from_slices(NODES, beta_t, sigma_t)
        np.testing.assert_allclose(beta_f.numpy(), BETA_FWD, rtol=1e-12)
        np.testing.assert_allclose(sigma_f.numpy(), SIGMA_FWD, rtol=1e-12)
        self.assertEqual(floored, 0)
        self.assertAlmostEqual(float(beta_t[0]), BETA_FWD[0], places=14)          # first slice = first piece
        self.assertTrue(BETA_FWD[1] < float(beta_t[1]) < BETA_FWD[0])            # weighted average in between
        self.assertAlmostEqual(float(sigma_t[1]) ** 2, (0.25 ** 2 * 0.5 + 0.2 ** 2 * 0.5), places=14)
        constant = DisplacedDiffusionModel(model._equity, NODES, [0.6] * 3, SIGMA_FWD)
        np.testing.assert_allclose(constant.effective_parameters([0.3, 1.7, 4.0])[0].numpy(), 0.6, rtol=1e-14)


class TestCalibration(unittest.TestCase):
    def setUp(self):
        self.mkt = dd_market()
        self.eq = self.mkt.get_equity("DD")

    def test_recovers_the_generating_parameters(self):
        model = DisplacedDiffusionModel.from_equity(self.eq)
        beta_f, sigma_f = model.forward_parameters
        np.testing.assert_allclose(beta_f.numpy(), BETA_FWD, rtol=1e-6)
        np.testing.assert_allclose(sigma_f.numpy(), SIGMA_FWD, rtol=1e-7)
        report = model.calibration
        self.assertLess(report.max_error_volpts.max(), 1e-5)
        self.assertFalse(report.beta_at_bound.any())
        for K in (80.0, 100.0, 125.0):
            self.assertAlmostEqual(model.implied_vol(K, 1.0), float(self.eq.vol_surface.volatility(K, 1.0)) if K in STRIKES
                                   else model.implied_vol(K, 1.0), places=7)

    def gradient_vs_recalibration(self, mkt, ticker, strike, maturity, nodes):
        """AAD through the calibration (implicit function theorem) vs bump-and-recalibrate central differences."""
        eq = mkt.get_equity(ticker)
        matrix = eq.vol_surface.volatility_matrix
        with tf.GradientTape() as tape:
            price = DisplacedDiffusionModel.from_equity(eq).vanilla_price(strike, maturity)
        d_vol, d_spot = tape.gradient(price, [matrix, eq.spot])

        def reprice():
            return float(DisplacedDiffusionModel.from_equity(eq).vanilla_price(strike, maturity))

        base, h = matrix.numpy(), 1e-5
        for i, j in nodes:
            out = []
            for sgn in (1, -1):
                bumped = base.copy()
                bumped[i, j] += sgn * h
                matrix.assign(bumped)
                out.append(reprice())
            matrix.assign(base)
            with self.subTest(ticker=ticker, node=(i, j)):
                self.assertAlmostEqual(float(d_vol[i, j]), (out[0] - out[1]) / (2 * h), delta=1e-5 * abs(float(d_vol[i, j])) + 1e-7)
        s0, out = float(eq.spot.numpy()), []
        for sgn in (1, -1):
            eq.spot.assign(s0 * (1 + sgn * 1e-6))
            out.append(reprice())
        eq.spot.assign(s0)
        self.assertAlmostEqual(float(d_spot), (out[0] - out[1]) / (2e-6 * s0), delta=1e-6)

    @slow
    def test_greeks_through_the_calibration(self):
        """Interior optimum (DD market) and beta on its bound (synthetic SSVI market): vega per node and delta."""
        self.gradient_vs_recalibration(self.mkt, "DD", 95.0, 1.0, [(1, 4), (1, 0), (1, 8), (0, 3), (2, 4)])
        ssvi = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=(("EUR", 1), ("GBP", 1), ("USD", 1)))
        surface = ssvi.get_equity("TICKER1").vol_surface
        k = list(surface.strike)[4]
        self.gradient_vs_recalibration(ssvi, "TICKER1", k, float(surface.maturity[3]), [(3, 4), (3, 0), (3, 7)])

    @slow
    def test_steep_equity_skew_is_out_of_reach(self):
        """Synthetic SSVI smiles are steeper than the normal skew: beta on its lower bound, ATM still within
        1 vol point (vega-weighted fit), the wings off."""
        tq.Settings.evaluation_date = EVAL_DATE
        mkt = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=(("EUR", 1), ("GBP", 1), ("USD", 1)))
        report = DisplacedDiffusionModel.from_equity(mkt.get_equity("TICKER1")).calibration
        self.assertTrue(report.beta_at_bound.all())
        self.assertLess(report.atm_error_volpts.abs().max(), 1.0)
        self.assertGreater(report.max_error_volpts.iloc[0], 5.0)
        self.assertLess(report.max_error_volpts.iloc[-1], report.max_error_volpts.iloc[0])

    def test_invalid_inputs(self):
        eq = make_market().get_equity("NOVOL")
        with self.assertRaises(ValueError):
            DisplacedDiffusionModel.from_equity(eq)
        with self.assertRaises(ValueError):
            DisplacedDiffusionModel(self.eq, [1.0, 0.5], [0.5, 0.5], [0.2, 0.2])
        with self.assertRaises(ValueError):
            DisplacedDiffusionModel(self.eq, [0.5, 1.0], [0.5, -0.1], [0.2, 0.2])
        with self.assertRaises(ValueError):
            DisplacedDiffusionModel(self.eq, [0.5, 1.0], [0.5], [0.2, 0.2])


class TestMonteCarlo(unittest.TestCase):
    N = 200_000

    def setUp(self):
        tq.Settings.evaluation_date = EVAL_DATE

    def terminal(self, model, times, seed=3):
        dw = tf.random.stateless_normal([self.N, len(times)], seed=[seed, 0], dtype=tf.float64)
        return model.evolve(times, dw).numpy()

    def test_constant_beta_is_exact(self):
        """Constant forward beta: the slices are exact, the MC equals the closed form within 3 SE."""
        mkt = dd_market([0.4] * 3, SIGMA_FWD)
        model = DisplacedDiffusionModel.from_equity(mkt.get_equity("DD"))
        grid = [0.25, 0.5, 0.8, 1.0, 1.6, 2.0]
        paths = self.terminal(model, grid)
        for col, T in ((1, 0.5), (5, 2.0)):
            df = float(mkt.get_ir_curve(tq.Currency.EUR).discount(T))
            for K in (70.0, 100.0, 130.0):
                pay = df * np.maximum(paths[:, col] - K, 0.0)
                with self.subTest(T=T, K=K):
                    self.assertLess(abs(pay.mean() - float(model.vanilla_price(K, T))), 3 * pay.std() / np.sqrt(self.N))

    def test_time_dependent_beta_reprices_the_slices_approximately(self):
        """Forward betas 0.8 / 0.5 / 0.3: the MC smile at the nodes is the market one up to the skew averaging
        (within 0.3 vol points on 70-130%)."""
        mkt = dd_market()
        eq = mkt.get_equity("DD")
        model = DisplacedDiffusionModel.from_equity(eq)
        paths = self.terminal(model, NODES)
        for col, T in enumerate(NODES):
            F = float(eq.forward(T))
            for K in (70.0, 100.0, 130.0):
                k = K / F
                mc = _black_implied_vol(float(np.mean(np.maximum(paths[:, col] / F - k, 0.0))), k, T)
                with self.subTest(T=T, K=K):
                    self.assertLess(abs(mc - float(eq.vol_surface.volatility(K, T))), 3e-3)

    @slow
    def test_steps_across_the_pieces(self):
        """A grid that does not hit the nodes (steps across pieces with different beta) keeps the slice law:
        coarse (7 steps) and fine (1 step per day-ish) grids give the node-grid price within 3 SE."""
        mkt = dd_market([0.9, 0.2, 0.6], SIGMA_FWD)
        model = DisplacedDiffusionModel.from_equity(mkt.get_equity("DD"))
        prices = {}
        for name, grid in (("nodes", [0.5, 1.0]), ("coarse", list(np.linspace(0.0, 1.0, 8)[1:])),
                           ("fine", list(np.linspace(0.0, 1.0, 301)[1:]))):
            dw = tf.random.stateless_normal([self.N, len(grid)], seed=[11, 0], dtype=tf.float64)
            s_t = model.evolve(grid, dw, observation_times=[1.0]).numpy()[:, 0]
            pay = np.maximum(s_t - 100.0, 0.0)
            prices[name] = (pay.mean(), pay.std() / np.sqrt(self.N))
        for name in ("coarse", "fine"):
            with self.subTest(grid=name):
                self.assertLess(abs(prices[name][0] - prices["nodes"][0]), 3 * np.hypot(prices[name][1], prices["nodes"][1]))

    def test_forward_is_the_market_forward(self):
        """Discrete dividends: without correction the MC forward is F(t) within 3 SE, with it exactly."""
        eq = make_market().get_equity("DISC")
        times = [0.25, 0.5, 1.0]
        for correction in (False, True):
            model = DisplacedDiffusionModel.from_equity(eq, martingale_correction=correction)
            paths = self.terminal(model, times)
            for col, t in enumerate(times):
                F = float(eq.forward(t))
                with self.subTest(correction=correction, t=t):
                    if correction:
                        self.assertAlmostEqual(paths[:, col].mean() / F, 1.0, places=12)
                    else:
                        self.assertLess(abs(paths[:, col].mean() - F), 3 * paths[:, col].std() / np.sqrt(self.N))

    @slow
    def test_vanilla_mc_pricer(self):
        """VanillaMCPricer(model=DisplacedDiffusionModel): price = closed form within 3 SE; delta and node vega
        (through the calibration) vs common-random-numbers bumps."""
        mkt = dd_market()
        eq = mkt.get_equity("DD")
        expiry = date(2027, 5, 15)
        T = eq.vol_surface.daycounter.year_fraction(EVAL_DATE, expiry)
        pricer = tq.VanillaMCPricer(model=DisplacedDiffusionModel, n_paths=100_000, n_steps=20, seed=5)
        opt = make_option(expiry, "Call", 105.0, underlying="DD")
        pricer.price(opt, mkt, autodiff=True)
        self.assertLess(abs(float(opt.price) - float(DisplacedDiffusionModel.from_equity(eq).vanilla_price(105.0, T))),
                        3 * float(opt.standard_error))
        d_spot, d_vol = pricer.tape.gradient(opt.price, [eq.spot, eq.vol_surface.volatility_matrix])

        def reprice():
            o = make_option(expiry, "Call", 105.0, underlying="DD")
            tq.VanillaMCPricer(model=DisplacedDiffusionModel, n_paths=100_000, n_steps=20, seed=5).price(o, mkt)
            return float(o.price)

        out = []
        for sgn in (1, -1):
            eq.spot.assign(S0 + sgn * 1e-3)
            out.append(reprice())
        eq.spot.assign(S0)
        self.assertAlmostEqual(float(d_spot), (out[0] - out[1]) / 2e-3, delta=1e-4)
        matrix, base, out = eq.vol_surface.volatility_matrix, eq.vol_surface.volatility_matrix.numpy(), []
        for sgn in (1, -1):
            bumped = base.copy()
            bumped[1, 5] += sgn * 1e-5
            matrix.assign(bumped)
            out.append(reprice())
        matrix.assign(base)
        self.assertAlmostEqual(float(d_vol[1, 5]), (out[0] - out[1]) / 2e-5, delta=1e-3 * abs(float(d_vol[1, 5])))


