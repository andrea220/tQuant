"""HestonSLVModel: leverage on a Heston market, local vol marginals, forward, greeks (Heston held), pricer wiring.

Light by design: given Heston parameters (no Heston calibration in the model tests), the E[v | X] table calibrated
on 20k particles up to 1Y, a few thousand pricing paths; checks of the model's defining properties rather than pricing
precision. Vega per node against bumps: tests/test_slv_vega.py.
"""

import unittest
from datetime import date, timedelta

import numpy as np
import tensorflow as tf

import tensorquant as tq

from markers import slow
from test_black_scholes import make_market
from test_heston import TRUTH, heston_market

EVAL_DATE = date(2026, 5, 15)
SMALL = (("EUR", 1), ("GBP", 1), ("USD", 1))
GRID = np.arange(1, 21) / 20.0          # 1Y, 20 steps


def ssvi_equity():
    tq.Settings.evaluation_date = EVAL_DATE
    mkt = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=SMALL)
    return mkt, mkt.get_equity("TICKER1")


def normals(n_paths, n_steps, seed=1):
    return tf.random.stateless_normal([n_paths, n_steps, 2], seed=[seed, 0], dtype=tf.float64)


LIGHT = dict(horizon=1.0, n_particles=20_000)


def slv(eq, mixing=1.0, **kwargs):
    """SLV on given Heston parameters (TRUTH) and the local vol of *eq*: leverage calibrated on *eq* up to 1Y."""
    return tq.HestonSLVModel(tq.HestonModel(**TRUTH), mixing=mixing, **{**LIGHT, **kwargs}).process(eq)


def autocallable(strike, underlying):
    cal = tq.TARGET()
    mf = tq.BusinessDayConvention.ModifiedFollowing
    sg = tq.ScheduleGenerator(cal, mf)
    end = cal.advance(EVAL_DATE, 2, tq.TimeUnit.Years, mf)
    cfix = sg.generate(EVAL_DATE, end, 6, tq.TimeUnit.Months)[1:]
    afix = sg.generate(cal.advance(EVAL_DATE, 1, tq.TimeUnit.Years, mf), end, 6, tq.TimeUnit.Months)
    return tq.AutocallableOption(
        ccy=tq.Currency.EUR, notional=1.0, start_date=EVAL_DATE, end_date=end, strike=strike,
        coupon_fixing_dates=cfix, coupon_payment_dates=cfix, coupon_rates=[4.0], coupon_barriers=[80.0], memory=False,
        autocall_fixing_dates=afix, autocall_payment_dates=afix, autocall_barrier=[100.0], payoff_barrier=80.0,
        underlying=underlying)


class TestModel(unittest.TestCase):
    def setUp(self):
        tq.Settings.evaluation_date = EVAL_DATE

    @slow
    def test_heston_market_has_unit_leverage(self):
        """Smile generated by the same Heston: L^2 = sigma_LV^2 / E[v | X] stays at 1 (up to the particle estimator)."""
        eq = heston_market().get_equity("HES")
        _, _, lev = slv(eq).simulate(GRID, normals(20_000, len(GRID), seed=2))
        q = np.quantile(lev.numpy()[:, -1], [0.05, 0.5, 0.95])
        self.assertAlmostEqual(q[1], 1.0, delta=0.04)
        self.assertTrue(0.85 < q[0] and q[2] < 1.15, q)

    @slow
    def test_marginals_are_the_local_vol_ones(self):
        """SSVI market (not Heston): for any mixing the 1Y marginal is the local vol one (calls at 90/100/110% of
        the forward within 4 SE of the local vol model), while the leverage departs from 1."""
        _, eq = ssvi_equity()
        F = float(eq.forward(1.0))
        lv_paths = tq.LocalVolatilityModel.from_equity(eq).evolve(
            GRID, tf.random.stateless_normal([8_000, len(GRID)], seed=[3, 0], dtype=tf.float64),
            observation_times=[1.0]).numpy()[:, 0]
        for mixing in (1.0, 0.1):
            x, _, lev = slv(eq, mixing).simulate(GRID, normals(8_000, len(GRID)))
            paths = slv(eq, mixing).evolve(GRID, normals(8_000, len(GRID)), observation_times=[1.0]).numpy()[:, 0]
            for k in (0.9, 1.0, 1.1):
                a, b = np.maximum(paths - k * F, 0), np.maximum(lv_paths - k * F, 0)
                se = np.hypot(a.std(), b.std()) / np.sqrt(8_000)
                with self.subTest(mixing=mixing, k=k):
                    self.assertLess(abs(a.mean() - b.mean()), 4 * se)
            if mixing == 1.0:
                self.assertGreater(np.std(lev.numpy()[:, -1]), 0.05)

    def test_forward_is_the_market_forward(self):
        """Discrete dividends: forward = F(t) within 3 SE without the sample correction, exactly with it."""
        eq = make_market().get_equity("DISC")
        times = [0.25, 0.5, 1.0]
        dw = normals(5_000, len(GRID), seed=5)
        for correction in (False, True):
            paths = slv(eq, martingale_correction=correction).evolve(GRID, dw, observation_times=times).numpy()
            for col, t in enumerate(times):
                F = float(eq.forward(t))
                with self.subTest(correction=correction, t=t):
                    if correction:
                        self.assertAlmostEqual(paths[:, col].mean() / F, 1.0, places=12)
                    else:
                        self.assertLess(abs(paths[:, col].mean() - F), 3 * paths[:, col].std() / np.sqrt(5_000))

    def test_invalid_inputs(self):
        eq = heston_market().get_equity("HES")
        heston = tq.HestonModel(**TRUTH)
        for kwargs in (dict(mixing=0.0), dict(mixing=1.5), dict(n_nodes=1), dict(n_particles=10)):
            with self.assertRaises(ValueError):
                tq.HestonSLVModel(heston, **kwargs)
        model = tq.HestonSLVModel(heston, horizon=0.5, n_particles=2_000).process(eq)
        self.assertEqual((model.size(), model.noise_size()), (2, 2))
        with self.assertRaises(ValueError):
            model.evolve([0.25, 0.5], tf.zeros([1000, 2], tf.float64))
        with self.assertRaises(ValueError):
            model.evolve([0.5, 1.0, 1.5], normals(500, 3))                 # steps beyond the table (horizon 0.5)


class TestGreeksAndPricers(unittest.TestCase):
    """SLV risk convention: Heston parameters held, leverage moving with the market (local vol, forward, and the
    E[v | X] table through its calibration)."""

    @slow
    def test_vanilla_greeks_reach_the_market(self):
        """1Y ATM call, leverage calibrated inside the tape (one backward pass through calibration and pricing):
        AAD delta and vega per node are finite and of the Black-Scholes (sticky strike) size (within 15%: few
        paths)."""
        mkt, eq = ssvi_equity()
        surface = eq.vol_surface
        K = float(surface.strike[4])
        df = float(eq.discount_curve.discount(1.0))
        with tf.GradientTape() as tape:
            process = tq.HestonSLVProcess.from_equity(eq, maturity=1.0, heston=tq.HestonModel(**TRUTH).process(eq),
                                                      n_particles=20_000)
            s_t = process.evolve(GRID, normals(5_000, len(GRID)), observation_times=[1.0])[:, 0]
            price = df * tf.reduce_mean(tf.maximum(s_t - K, 0.0))
        delta, vega = tape.gradient(price, [eq.spot, surface.volatility_matrix])
        self.assertTrue(np.all(np.isfinite(vega.numpy())))
        option = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Call, K,
                                  underlying="TICKER1")
        bs = tq.BlackScholesPricer()
        bs.price(option, mkt, autodiff=True)
        bs_delta, bs_vega = bs.tape.gradient(option.price, [eq.spot, surface.volatility_matrix])
        self.assertAlmostEqual(float(delta) / float(bs_delta), 1.0, delta=0.15)
        self.assertAlmostEqual(float(tf.reduce_sum(vega)) / float(tf.reduce_sum(bs_vega)), 1.0, delta=0.15)

    @slow
    def test_pricers_run_with_the_slv(self):
        """VanillaMCPricer and AutocallableMCPricer build the SLV by from_equity (Heston calibrated on the
        Heston market): the put is the Black-Scholes one within the MC error, the autocallable price is finite."""
        mkt = heston_market()
        option = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Put,
                                  90.0, underlying="HES")
        tq.VanillaMCPricer(model=tq.HestonSLVModel, n_paths=2_000, n_steps=10, seed=3).price(option, mkt)
        reference = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Put,
                                     90.0, underlying="HES")
        tq.BlackScholesPricer().price(reference, mkt)
        self.assertLess(abs(float(option.price) - float(reference.price)), 4 * float(option.standard_error) + 0.05)
        product = autocallable(100.0, "HES")
        pricer = tq.AutocallableMCPricer(model=tq.HestonSLVModel, n_paths=2_000, seed=7, max_time_step=1 / 12)
        pricer.price(product, mkt)
        self.assertTrue(np.isfinite(float(product.price)))
        self.assertEqual(pricer.paths.shape, (2_000, len(pricer.date_grid)))


if __name__ == "__main__":
    unittest.main()
