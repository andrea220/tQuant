"""HestonSLVModel: particle-method leverage on the market forward, smile repricing, limits, greeks (Heston held)."""

import unittest
from datetime import date, timedelta

import numpy as np
import tensorflow as tf

import tensorquant as tq
from tensorquant.models.displaceddiffusion import _black_implied_vol

from test_black_scholes import make_market
from test_heston import TRUTH, heston_market
from markers import slow

EVAL_DATE = date(2026, 5, 15)
SMALL = (("EUR", 1), ("GBP", 1), ("USD", 1))


def ssvi_equity():
    tq.Settings.evaluation_date = EVAL_DATE
    mkt = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=SMALL)
    return mkt, mkt.get_equity("TICKER1")


def normals(n_paths, n_steps, seed=1):
    return tf.random.stateless_normal([n_paths, n_steps, 2], seed=[seed, 0], dtype=tf.float64)


def autocallable(strike, underlying):
    cal = tq.TARGET()
    mf = tq.BusinessDayConvention.ModifiedFollowing
    sg = tq.ScheduleGenerator(cal, mf)
    end = cal.advance(EVAL_DATE, 3, tq.TimeUnit.Years, mf)
    cfix = sg.generate(EVAL_DATE, end, 6, tq.TimeUnit.Months)[1:]
    afix = sg.generate(cal.advance(EVAL_DATE, 1, tq.TimeUnit.Years, mf), end, 6, tq.TimeUnit.Months)
    return tq.AutocallableOption(
        ccy=tq.Currency.EUR, notional=1.0, start_date=EVAL_DATE, end_date=end, strike=strike,
        coupon_fixing_dates=cfix, coupon_payment_dates=cfix, coupon_rates=[4.0], coupon_barriers=[80.0], memory=False,
        autocall_fixing_dates=afix, autocall_payment_dates=afix, autocall_barrier=[100.0], payoff_barrier=80.0,
        underlying=underlying)


class TestSmileAndLimits(unittest.TestCase):
    def setUp(self):
        tq.Settings.evaluation_date = EVAL_DATE

    @slow
    def test_reprices_the_market_smile(self):
        """Synthetic SSVI market (Heston alone misses the short wings): the SLV MC smile at 1Y and 3Y is the
        market one within 0.6 vol points on 70-130% (OTM options), for mixing 1 and 0.5 (the local vol bound of
        test_vanilla_mc; 25 steps a year)."""
        _, eq = ssvi_equity()
        surface = eq.vol_surface
        nodes = [float(surface.maturity[3]), float(surface.maturity[6])]
        grid = np.unique(np.concatenate([np.arange(1, int(nodes[-1] * 25) + 1) / 25.0, nodes]))
        for mixing in (1.0, 0.5):
            model = tq.HestonSLVModel.from_equity(eq, mixing=mixing)
            paths = model.evolve(grid, normals(50_000, len(grid)), observation_times=nodes).numpy()
            for col, T in enumerate(nodes):
                F = float(eq.forward(T))
                for K in surface.strike[1:-1]:
                    k = float(K) / F
                    x = paths[:, col] / F
                    otm = np.maximum(x - k, 0).mean() if k >= 1 else np.maximum(k - x, 0).mean() + 1 - k
                    with self.subTest(mixing=mixing, T=T, K=K):
                        self.assertLess(abs(_black_implied_vol(otm, k, T) - float(surface.volatility(K, T))), 6e-3)

    @slow
    def test_heston_market_has_unit_leverage(self):
        """Smile generated by Heston: the leverage stays at 1 (up to the estimator) and the SLV smile is the Heston
        (COS) one within 0.5 vol points at 70/100/130% (the local vol model alone is 0.3 off on this grid)."""
        mkt = heston_market()
        eq = mkt.get_equity("HES")
        model = tq.HestonSLVModel.from_equity(eq)
        grid = np.arange(1, 51) / 25.0
        dw = normals(100_000, 50, seed=2)
        _, _, lev = model.simulate(grid, dw)
        for col in (24, 49):
            q = np.quantile(lev.numpy()[:, col], [0.05, 0.5, 0.95])
            self.assertAlmostEqual(q[1], 1.0, delta=0.03)
            self.assertTrue(0.88 < q[0] and q[2] < 1.12, q)
        paths = model.evolve(grid, dw, observation_times=[1.0, 2.0]).numpy()
        heston = tq.HestonModel(eq, **TRUTH)
        for col, T in enumerate((1.0, 2.0)):
            F = float(eq.forward(T))
            for K in (70.0, 100.0, 130.0):
                k, x = K / F, paths[:, col] / F
                otm = np.maximum(x - k, 0).mean() if k >= 1 else np.maximum(k - x, 0).mean() + 1 - k
                with self.subTest(T=T, K=K):
                    self.assertLess(abs(_black_implied_vol(otm, k, T) - heston.implied_vol(K, T)), 5e-3)

    @slow
    def test_mixing_interpolates_local_vol_and_stochastic_vol(self):
        """3Y autocallable: small mixing = local vol within 4 SE; full mixing far from it (forward smile)."""
        mkt, eq = ssvi_equity()
        spot = float(eq.spot.numpy())
        prices = {}
        for name, model in (("LV", tq.LocalVolatilityModel), ("SLV", tq.HestonSLVModel)):
            product = autocallable(spot, "TICKER1")
            tq.AutocallableMCPricer(model=model, n_paths=20_000, seed=7).price(product, mkt)
            prices[name] = (float(product.price), float(product.standard_error))
        small = tq.HestonSLVModel.from_equity(eq, mixing=0.05)
        pricer = tq.AutocallableMCPricer(model=tq.LocalVolatilityModel, n_paths=20_000, seed=7)
        pricer._model = type("SmallMixing", (), {"from_equity": staticmethod(lambda *a, **k: small)})
        product = autocallable(spot, "TICKER1")
        pricer.price(product, mkt)
        se = np.hypot(prices["LV"][1], float(product.standard_error))
        self.assertLess(abs(float(product.price) - prices["LV"][0]), 4 * se)
        self.assertGreater(abs(prices["SLV"][0] - prices["LV"][0]), 4 * np.hypot(prices["SLV"][1], prices["LV"][1]))

    def test_forward_is_the_market_forward(self):
        """Discrete dividends: forward = F(t) within 3 SE without the sample correction, exactly with it (given
        Heston parameters: the property does not depend on the calibration)."""
        eq = make_market().get_equity("DISC")
        times = [0.25, 0.5, 1.0]
        grid = np.arange(1, 21) / 20.0
        dw = normals(50_000, 20, seed=5)
        heston, local_vol = tq.HestonModel(eq, **TRUTH), tq.LocalVolatilityModel.from_equity(eq)
        for correction in (False, True):
            model = tq.HestonSLVModel(eq, heston, local_vol, martingale_correction=correction)
            paths = model.evolve(grid, dw, observation_times=times).numpy()
            for col, t in enumerate(times):
                F = float(eq.forward(t))
                with self.subTest(correction=correction, t=t):
                    if correction:
                        self.assertAlmostEqual(paths[:, col].mean() / F, 1.0, places=12)
                    else:
                        self.assertLess(abs(paths[:, col].mean() - F), 3 * paths[:, col].std() / np.sqrt(50_000))

    def test_invalid_inputs(self):
        mkt = heston_market()
        eq = mkt.get_equity("HES")
        heston = tq.HestonModel(eq, **TRUTH)
        lv = tq.LocalVolatilityModel.from_equity(eq)
        for kwargs in (dict(mixing=0.0), dict(mixing=1.5), dict(n_nodes=1)):
            with self.assertRaises(ValueError):
                tq.HestonSLVModel(eq, heston, lv, **kwargs)
        model = tq.HestonSLVModel(eq, heston, lv)
        self.assertEqual((model.size(), model.noise_size()), (2, 2))
        with self.assertRaises(ValueError):
            model.evolve([0.5, 1.0], tf.zeros([1000, 2], tf.float64))
        with self.assertRaises(ValueError):
            model.evolve([0.5, 1.0], normals(50, 2))                       # fewer paths than nodes


class TestGreeks(unittest.TestCase):
    """SLV risk convention: Heston parameters held, leverage moving with the market (local vol, forward)."""

    def setUp(self):
        self.mkt, self.eq = ssvi_equity()

    @slow
    def test_vanilla_greeks_vs_bumps_and_black_scholes(self):
        """1Y ATM call on a vol node: AAD delta / parallel vega = common-random-numbers bumps (Heston held) within
        1%, and the Black-Scholes (sticky strike) greeks within 3% (particle estimator)."""
        eq, surface = self.eq, self.eq.vol_surface
        K, T = float(surface.strike[4]), 1.0
        grid = np.arange(1, 51) / 50.0
        dw = normals(50_000, 50)
        df = float(eq.discount_curve.discount(T))
        held = {k: float(v) for k, v in tq.HestonModel.from_equity(eq).parameters.items()}

        def price():
            model = tq.HestonSLVModel(eq, tq.HestonModel(eq, **held), tq.LocalVolatilityModel.from_equity(eq))
            s_t = model.evolve(grid, dw, observation_times=[T])[:, 0]
            return df * tf.reduce_mean(tf.maximum(s_t - K, 0.0))

        with tf.GradientTape() as tape:
            p = price()
        delta, vega = tape.gradient(p, [eq.spot, surface.volatility_matrix])
        spot, out = float(eq.spot.numpy()), []
        for h in (0.5, -0.5):
            eq.spot.assign(spot + h)
            out.append(float(price()))
        eq.spot.assign(spot)
        self.assertAlmostEqual(float(delta) / ((out[0] - out[1]) / 1.0), 1.0, delta=0.01)
        base, out = surface.volatility_matrix.numpy(), []
        for h in (1e-4, -1e-4):
            surface.volatility_matrix.assign(base + h)
            out.append(float(price()))
        surface.volatility_matrix.assign(base)
        self.assertAlmostEqual(float(tf.reduce_sum(vega)) / ((out[0] - out[1]) / 2e-4), 1.0, delta=0.01)

        option = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Call, K,
                                  underlying="TICKER1")
        bs = tq.BlackScholesPricer()
        bs.price(option, self.mkt, autodiff=True)
        bs_delta, bs_vega = bs.tape.gradient(option.price, [eq.spot, surface.volatility_matrix])
        self.assertAlmostEqual(float(delta) / float(bs_delta), 1.0, delta=0.03)
        self.assertAlmostEqual(float(tf.reduce_sum(vega)) / float(tf.reduce_sum(bs_vega)), 1.0, delta=0.03)

    @slow
    def test_pricers_and_stable_autocallable_greeks(self):
        """VanillaMCPricer and AutocallableMCPricer run with the SLV; the autocallable AAD greeks are finite and
        of the local vol order (no blow-up from differentiating the conditional expectation)."""
        spot = float(self.eq.spot.numpy())
        greeks = {}
        for model in (tq.LocalVolatilityModel, tq.HestonSLVModel):
            product = autocallable(spot, "TICKER1")
            pricer = tq.AutocallableMCPricer(model=model, n_paths=10_000, seed=7, barrier_smoothing=0.01)
            pricer.price(product, self.mkt, autodiff=True)
            d_spot, d_vol = pricer.tape.gradient(product.price, [self.eq.spot, self.eq.vol_surface.volatility_matrix])
            greeks[model] = (float(d_spot), float(tf.reduce_sum(d_vol)))
        lv, slv = greeks[tq.LocalVolatilityModel], greeks[tq.HestonSLVModel]
        self.assertTrue(np.all(np.isfinite(slv)))
        self.assertLess(abs(slv[0]), 3 * abs(lv[0]) + 1e-3)
        self.assertLess(abs(slv[1] - lv[1]), 0.5 * abs(lv[1]))
        option = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Put,
                                  0.9 * spot, underlying="TICKER1")
        pricer = tq.VanillaMCPricer(model=tq.HestonSLVModel, n_paths=30_000, n_steps=25, seed=3)
        pricer.price(option, self.mkt)
        reference = tq.VanillaOption(tq.Currency.EUR, EVAL_DATE, EVAL_DATE + timedelta(days=365), tq.OptionType.Put,
                                     0.9 * spot, underlying="TICKER1")
        tq.BlackScholesPricer().price(reference, self.mkt)
        self.assertLess(abs(float(option.price) - float(reference.price)), 4 * float(option.standard_error) + 0.003 * float(reference.price))


if __name__ == "__main__":
    unittest.main()
