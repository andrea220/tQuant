"""HestonModel: characteristic function and COS prices, calibration (differentiable), QE-M Monte Carlo on the market forward."""

import unittest
from datetime import date

import numpy as np
import tensorflow as tf
from scipy.integrate import quad
from scipy.stats import norm

import tensorquant as tq
from tensorquant.markethandles.marketenvironment import MarketEnvironment
from tensorquant.markethandles.volatilitysurface import VolatilitySurface
from tensorquant.models.heston import (
    HestonModel, heston_characteristic_function, heston_cumulants, heston_price,
)
from tensorquant.timehandles.daycounter import DayCounter, DayCounterConvention

from test_black_scholes import make_market, make_option

EVAL_DATE = date(2026, 5, 15)
S0 = 100.0
A365 = DayCounterConvention.Actual365
TRUTH = dict(v0=0.05, kappa=1.2, theta=0.045, xi=0.6, rho=-0.7)
STRIKES = [60.0, 70.0, 80.0, 90.0, 100.0, 110.0, 120.0, 130.0, 140.0]
MATURITIES = [0.25, 0.5, 1.0, 2.0, 3.0, 5.0]
SMALL = (("EUR", 1), ("GBP", 1), ("USD", 1))


def cf_numpy(u, t, v0, kappa, theta, xi, rho):
    """Independent numpy characteristic function (same stable form)."""
    iu = 1j * u
    b = kappa - rho * xi * iu
    d = np.sqrt(b * b + xi * xi * (iu + u * u))
    g = (b - d) / (b + d)
    e = np.exp(-d * t)
    return np.exp(kappa * theta / xi ** 2 * ((b - d) * t - 2 * np.log((1 - g * e) / (1 - g)))
                  + (b - d) / xi ** 2 * (1 - e) / (1 - g * e) * v0)


def lewis_call(k, t, p):
    """Lewis (2001): C = 1 - sqrt(k) / pi int_0^inf Re[e^{-iu ln k} phi(u - i/2)] / (u^2 + 1/4) du (per unit forward)."""
    f = lambda u: (np.exp(-1j * u * np.log(k)) * cf_numpy(u - 0.5j, t, **p)).real / (u * u + 0.25)
    return 1.0 - np.sqrt(k) / np.pi * quad(f, 0, np.inf, limit=1000, epsabs=1e-14, epsrel=1e-13)[0]


def black(k, vol, t):
    sd = vol * np.sqrt(t)
    d1 = -np.log(k) / sd + 0.5 * sd
    return norm.cdf(d1) - k * norm.cdf(d1 - sd)


def heston_market(params=TRUTH) -> MarketEnvironment:
    """Market whose smile is generated by a Heston model with *params*."""
    tq.Settings.evaluation_date = EVAL_DATE
    surface = VolatilitySurface(EVAL_DATE, None, DayCounter(A365), STRIKES, MATURITIES,
                                [[0.2] * len(STRIKES)] * len(MATURITIES))
    mkt = MarketEnvironment(market={
        "IR:EUR:ESTR:SPOT": tq.RateCurve(EVAL_DATE, [0.5, 1.0, 2.0, 5.0], [0.020, 0.022, 0.024, 0.026], "LINEAR", A365),
        "EQ:EUR:HES:SPOT": S0, "EQ:EUR:HES:REPO": 0.005, "EQ:EUR:HES:DIVYIELD": 0.02, "EQ:EUR:HES:VOL": surface,
    })
    truth = HestonModel(mkt.get_equity("HES"), **params)
    surface.volatility_matrix.assign([[truth.implied_vol(K, T) for K in STRIKES] for T in MATURITIES])
    return mkt


class TestClosedForm(unittest.TestCase):
    def test_characteristic_function(self):
        """phi(0) = 1, martingale phi(-i) = 1, = independent numpy; cumulants vs finite differences of ln phi."""
        u = np.array([0.0, 0.7, 3.0, 25.0])
        for t in (0.1, 2.0):
            np.testing.assert_allclose(heston_characteristic_function(u, t, **TRUTH).numpy(), cf_numpy(u, t, **TRUTH),
                                       rtol=1e-13, atol=1e-15)
            self.assertAlmostEqual(abs(cf_numpy(-1j, t, **TRUTH) - 1.0), 0.0, places=13)
            c1, c2 = (float(np.ravel(v)[0]) for v in heston_cumulants(t, **TRUTH))
            lp = lambda x: np.log(cf_numpy(x, t, **TRUTH))
            h = 1e-4
            self.assertAlmostEqual(c1, ((lp(h) - lp(-h)) / (2j * h)).real, places=9)
            self.assertAlmostEqual(c2 / (-(lp(h) + lp(-h)).real / h ** 2), 1.0, places=5)

    def test_cos_vs_lewis_quadrature(self):
        k = np.array([0.5, 0.8, 1.0, 1.2, 1.6])
        for t in (1 / 52, 1 / 12, 1.0, 5.0, 10.0):
            cos = heston_price(k[None, :], [t], **TRUTH).numpy()[0]
            with self.subTest(t=t):
                np.testing.assert_allclose(cos, [lewis_call(kk, t, TRUTH) for kk in k], atol=1e-12)

    def test_black_scholes_limit_and_parity(self):
        k = np.array([[0.6, 1.0, 1.5]])
        limit = heston_price(k, [2.0], 0.04, 1.0, 0.04, 1e-4, 0.0).numpy()[0]
        np.testing.assert_allclose(limit, black(k[0], 0.2, 2.0), atol=1e-9)
        call = heston_price(k, [1.5], **TRUTH).numpy()[0]
        put = heston_price(k, [1.5], **TRUTH, phi=-1.0).numpy()[0]
        np.testing.assert_allclose(call - put, 1.0 - k[0], atol=1e-15)
        self.assertTrue(np.all(put > 0.0))

    def test_negative_rho_gives_negative_skew(self):
        model = HestonModel(heston_market().get_equity("HES"), **TRUTH)
        vols = [model.implied_vol(K, 1.0) for K in (80.0, 100.0, 120.0)]
        self.assertGreater(vols[0], vols[1])
        self.assertGreater(vols[1], vols[2])
        with self.assertRaises(ValueError):
            HestonModel(model._equity, **dict(TRUTH, rho=-1.0))


class TestCalibration(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.mkt = heston_market()

    def setUp(self):
        tq.Settings.evaluation_date = EVAL_DATE

    def test_recovers_the_generating_parameters(self):
        model = HestonModel.from_equity(self.mkt.get_equity("HES"), initial=dict(kappa=3.0, xi=0.3, rho=-0.3))
        for name, value in TRUTH.items():
            self.assertAlmostEqual(float(model.parameters[name]) / value, 1.0, places=6, msg=name)
        report = model.calibration
        self.assertLess(report.max_error_volpts.max(), 1e-6)
        self.assertEqual(report.attrs["at_bound"], [])
        self.assertAlmostEqual(model.feller, 2 * 1.2 * 0.045 - 0.36, places=6)

    def gradient_vs_recalibration(self, mkt, ticker, strike, maturity, nodes, rel):
        """AAD through the calibration (implicit function theorem) vs bump-and-recalibrate central differences."""
        eq = mkt.get_equity(ticker)
        matrix = eq.vol_surface.volatility_matrix
        with tf.GradientTape() as tape:
            price = HestonModel.from_equity(eq).vanilla_price(strike, maturity)
        d_vol, d_spot = tape.gradient(price, [matrix, eq.spot])

        def reprice():
            return float(HestonModel.from_equity(eq).vanilla_price(strike, maturity))

        base, h = matrix.numpy(), 1e-5
        for i, j in nodes:
            out = []
            for sgn in (1, -1):
                bumped = base.copy()
                bumped[i, j] += sgn * h
                matrix.assign(bumped)
                out.append(reprice())
            matrix.assign(base)
            fd = (out[0] - out[1]) / (2 * h)
            with self.subTest(ticker=ticker, node=(i, j)):
                self.assertAlmostEqual(float(d_vol[i, j]), fd, delta=rel * abs(fd) + 1e-8)
        s0, out = float(eq.spot.numpy()), []
        for sgn in (1, -1):
            eq.spot.assign(s0 * (1 + sgn * 1e-6))
            out.append(reprice())
        eq.spot.assign(s0)
        fd = (out[0] - out[1]) / (2e-6 * s0)
        self.assertAlmostEqual(float(d_spot), fd, delta=rel * abs(fd))

    def test_greeks_through_the_calibration(self):
        """Vega per node and delta: Heston market (exact fit) and synthetic SSVI market (residuals)."""
        self.gradient_vs_recalibration(self.mkt, "HES", 95.0, 1.0, [(2, 4), (5, 8)], 1e-6)
        ssvi = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=SMALL)
        surface = ssvi.get_equity("TICKER1").vol_surface
        self.gradient_vs_recalibration(ssvi, "TICKER1", float(surface.strike[4]), 1.0, [(3, 4), (0, 4), (3, 0)], 1e-6)

    def test_synthetic_market_fit(self):
        """SSVI smiles: ATM within 1.5 vol points everywhere, wings within 1.5 from 1Y (steep short-term wings
        are beyond a 5-parameter Heston), parameters inside the bounds."""
        tq.Settings.evaluation_date = EVAL_DATE
        mkt = tq.generate_market(EVAL_DATE, seed=7, tickers_per_currency=SMALL)
        model = HestonModel.from_equity(mkt.get_equity("TICKER1"))
        report = model.calibration
        self.assertLess(report.atm_error_volpts.abs().max(), 1.5)
        self.assertLess(report[report.maturity >= 1.0].max_error_volpts.max(), 1.5)
        self.assertEqual(report.attrs["at_bound"], [])
        self.assertLess(float(model.parameters["rho"]), 0.0)

    def test_invalid_inputs(self):
        with self.assertRaises(ValueError):
            HestonModel.from_equity(make_market().get_equity("NOVOL"))


class TestMonteCarlo(unittest.TestCase):
    N = 200_000

    def setUp(self):
        tq.Settings.evaluation_date = EVAL_DATE

    def test_qe_vs_closed_form(self):
        """QE-M with 26 steps a year: calls at 70/100/130% within 3 SE of the COS price (Feller violated)."""
        mkt = heston_market()
        model = HestonModel(mkt.get_equity("HES"), **TRUTH, martingale_correction=False)
        self.assertLess(model.feller, 0.0)
        grid = np.arange(1, 53) / 26.0
        dw = tf.random.stateless_normal([self.N, len(grid), 2], seed=[3, 0], dtype=tf.float64)
        paths = model.evolve(grid, dw, observation_times=[1.0, 2.0]).numpy()
        curve = mkt.get_ir_curve(tq.Currency.EUR)
        for col, T in enumerate((1.0, 2.0)):
            for K in (70.0, 100.0, 130.0):
                pay = float(curve.discount(T)) * np.maximum(paths[:, col] - K, 0.0)
                with self.subTest(T=T, K=K):
                    self.assertLess(abs(pay.mean() - float(model.vanilla_price(K, T))), 3 * pay.std() / np.sqrt(self.N))

    def test_forward_is_the_market_forward(self):
        """Discrete dividends: QE-M forward = F(t) within 3 SE without the sample correction, exact with it."""
        eq = make_market().get_equity("DISC")
        times = [0.25, 0.5, 1.0]
        dw = tf.random.stateless_normal([self.N, 3, 2], seed=[5, 0], dtype=tf.float64)
        for correction in (False, True):
            paths = HestonModel(eq, **TRUTH, martingale_correction=correction).evolve(times, dw).numpy()
            for col, t in enumerate(times):
                F = float(eq.forward(t))
                with self.subTest(correction=correction, t=t):
                    if correction:
                        self.assertAlmostEqual(paths[:, col].mean() / F, 1.0, places=12)
                    else:
                        self.assertLess(abs(paths[:, col].mean() - F), 3 * paths[:, col].std() / np.sqrt(self.N))

    def test_variance_moments_and_shapes(self):
        """E[v_t] = theta + (v0 - theta) e^{-kappa t} within 3 SE, v >= 0; noise_size 2, dw shape checked."""
        model = HestonModel(heston_market().get_equity("HES"), **TRUTH)
        self.assertEqual((model.size(), model.noise_size()), (2, 2))
        grid = np.arange(1, 27) / 26.0
        _, v = model.simulate(grid, tf.random.stateless_normal([self.N, 26, 2], seed=[7, 0], dtype=tf.float64))
        v = v.numpy()[:, -1]
        mean = TRUTH["theta"] + (TRUTH["v0"] - TRUTH["theta"]) * np.exp(-TRUTH["kappa"])
        self.assertLess(abs(v.mean() - mean), 3 * v.std() / np.sqrt(self.N))
        self.assertGreaterEqual(v.min(), 0.0)
        with self.assertRaises(ValueError):
            model.evolve(grid, tf.zeros([10, 26], tf.float64))

    def test_vanilla_mc_pricer(self):
        """VanillaMCPricer(model=HestonModel): price = closed form within 3 SE; MC delta and vega by AAD (through
        the calibration) = the closed-form ones. Bump-and-reprice with common random numbers is no reference
        for QE: the variance scheme switches branch per path and step, so the estimator jumps when the
        parameters move (finite differences do not converge as the bump shrinks)."""
        mkt = heston_market()
        eq = mkt.get_equity("HES")
        matrix = eq.vol_surface.volatility_matrix
        expiry = date(2027, 5, 15)
        T = eq.vol_surface.daycounter.year_fraction(EVAL_DATE, expiry)
        with tf.GradientTape() as tape:
            closed = HestonModel.from_equity(eq).vanilla_price(105.0, T)
        cf_delta, cf_vega = tape.gradient(closed, [eq.spot, matrix])
        opt = make_option(expiry, "Call", 105.0, underlying="HES")
        mc = tq.VanillaMCPricer(model=HestonModel, n_paths=100_000, n_steps=26, seed=5)
        mc.price(opt, mkt, autodiff=True)
        self.assertLess(abs(float(opt.price) - float(closed)), 3 * float(opt.standard_error))
        delta, vega = mc.tape.gradient(opt.price, [eq.spot, matrix])
        self.assertAlmostEqual(float(delta) / float(cf_delta), 1.0, delta=0.02)
        self.assertAlmostEqual(float(tf.reduce_sum(vega)) / float(tf.reduce_sum(cf_vega)), 1.0, delta=0.02)
        self.assertAlmostEqual(float(vega[2, 5]) / float(cf_vega[2, 5]), 1.0, delta=0.1)


